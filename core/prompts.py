def build_id_route_hint(
    alias_map: "Mapping[str, str]",
    missing_report_ids: "Iterable[str]" = (),
) -> str:
    """Name the aliases the answer must cite on the exact report-id route."""
    parts = [ID_ROUTE_HINT]
    if alias_map:
        aliases = ", ".join(f"[{alias}]" for alias in alias_map)
        parts.append(ID_ROUTE_REPORT_LIST.format(aliases=aliases))
    missing = list(missing_report_ids)
    if missing:
        parts.append(
            ID_ROUTE_MISSING_HINT.format(report_ids=", ".join(missing))
        )
    return " ".join(parts)


def build_id_route_question(question: str, alias_map: "Mapping[str, str]") -> str:
    """
    Replace report ids that were retrieved with their alias, for the answer prompt
    only (fix pack H1a). The model then sees the same identity the context uses,
    instead of a report id it cannot find anywhere. The rewritten text is never
    shown to the user: the answer and citations come from the backend.
    """
    by_report = {report_id: alias for alias, report_id in alias_map.items()}

    def replace(match: "object") -> str:
        token = match.group(0)
        return by_report.get(token, token)

    return config.PATTERN_REPORT_ID.sub(replace, question or "")


