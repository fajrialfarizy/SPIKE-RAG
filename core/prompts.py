def _normalized_answer(text: str) -> str:
    """Case, whitespace and Markdown normalized form used for the refusal test."""
    without_markdown = config.PATTERN_NOT_FOUND_MARKDOWN.sub(" ", text or "")
    return " ".join(without_markdown.casefold().split())


def is_not_found_refusal(text: str) -> bool:
    """
    True when the model answered with the standard not-found sentence (fix H2).

    The first ``NOT_FOUND_ANSWER_PREFIX_CHARS`` normalized characters of
    NOT_FOUND_RESPONSE must match; a missing or slightly reworded second sentence
    still counts, because the model often stops after the first sentence.
    """
    if not (text or "").strip():
        return False
    prefix = _normalized_answer(NOT_FOUND_RESPONSE)[
        : config.NOT_FOUND_ANSWER_PREFIX_CHARS
    ]
    return bool(prefix) and _normalized_answer(text).startswith(prefix)


